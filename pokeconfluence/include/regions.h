#ifndef GUARD_REGIONS_H
#define GUARD_REGIONS_H

#include "global.h"
#include "constants/regions.h"
#include "constants/maps.h"

enum KantoSubRegion GetKantoSubregion(u32 mapSecId);

static inline enum Region GetRegionForSectionId(u32 sectionId)
{
    // POKE-CONFLUENCE: Johto mapsec band
    if (sectionId >= MAPSEC_JOHTO_AZALEA_TOWN && sectionId <= MAPSEC_JOHTO_APEX_SUMMIT)
        return REGION_JOHTO;
    if (sectionId >= KANTO_MAPSEC_START && sectionId < MAPSEC_SPECIAL_AREA)
        return REGION_KANTO;
    return REGION_HOENN;
}

// POKE-MULTIREGION: Johto maps live in their own map groups (gMapGroup_Johto1..4, generated by poke-crystal-maps), so the group
// tells the region even where a Johto map reuses a Kanto or Hoenn map section name.
static inline enum Region GetCurrentRegion(void)
{
    if (gSaveBlock1Ptr->location.mapGroup >= MAP_GROUP(MAP_JOHTO_OLIVINE_POKECENTER_1F))
        return REGION_JOHTO;
    return GetRegionForSectionId(gMapHeader.regionMapSectionId);
}

// Flag of the nth gym badge (0-7) of a region: Hoenn FLAG_BADGE01_GET.., Kanto FLAG_BADGE09_GET.., Johto in the Johto flag band.
u16 GetBadgeFlagForRegion(enum Region region, u32 index);

// POKE-MULTIREGION: behaviour that FireRed implements with a compile-time IS_FRLG (first-battle tutorial, old man) must
// also apply to battles fought in Kanto when the ROM is built as Emerald.
#define IS_FRLG_CTX (IS_FRLG || GetCurrentRegion() == REGION_KANTO)

#endif // GUARD_REGIONS_H
